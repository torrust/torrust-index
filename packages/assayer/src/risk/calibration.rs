/// Configuration for Platt calibration fitting.
///
/// The defaults are the specification's (´tab:config:calibration´).
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct PlattConfig {
    /// Calibration buffer capacity. Default: 2,000.
    pub n_cal_buf: usize,
    /// Periodic refit cadence (labels). Default: 200.
    pub n_refit: u32,
    /// Minimum total weighted samples per regime. Default: 30.
    pub n_cal_min: u32,
    /// Minimum positive weighted samples per regime. Default: 3.
    pub n_cal_pos: u32,
    /// Minimum negative weighted samples per regime. Default: 3.
    pub n_cal_neg: u32,
    /// Initial κ for both regimes. Default: 1.0.
    pub kappa_initial: f64,
    /// Search lower bound for κ. Default: 0.01.
    pub kappa_min: f64,
    /// Search upper bound for κ. Default: 100.0.
    pub kappa_max: f64,
    /// Recency weighting factor `γ_cal`. Default: 0.9998, the sister's own
    /// forgetting rate (´tab:risk:forgetting-rates´).
    pub gamma_cal: f64,
    /// Golden section tolerance in log(κ). Default: 1e-4.
    pub golden_tolerance: f64,
    /// Golden section max iterations. Default: 50.
    pub max_golden_iterations: u32,
    /// `δ_cal` threshold for drift accumulator reset. Default: 0.1.
    pub delta_cal_threshold: f64,
}

impl Default for PlattConfig {
    fn default() -> Self {
        Self {
            n_cal_buf: 2_000,
            n_refit: 200,
            n_cal_min: 30,
            n_cal_pos: 3,
            n_cal_neg: 3,
            kappa_initial: 1.0,
            kappa_min: 0.01,
            kappa_max: 100.0,
            gamma_cal: 0.9998,
            golden_tolerance: 1e-4,
            max_golden_iterations: 50,
            delta_cal_threshold: 0.1,
        }
    }
}

