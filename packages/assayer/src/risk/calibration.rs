    ///
    /// ´claim:risk:when-the-old-and-new-halves-of-the-buffer-disagree-the-fit-follows-the-newer-one´
    /// ´test:unit:recency-weighting-dominance´
    #[test]
    fn recency_weighting_dominance() {
        // When old entries suggest κ ≈ 1 and new entries
        // suggest κ ≈ 5, the fit should be pulled toward 5.
        //
        // Use γ_cal = 0.99 (aggressive) so the effect is pronounced.
        // At the default 0.9998 the oldest entry still retains ~67% of
        // the newest's weight — too gentle for a clear dominance test.
        let mut buffer = CalibrationBuffer::new(2_000);

        // 1000 old entries generated with true κ = 1.0
        for i in 0..1_000 {
            let rho = -5.0 + 10.0 * (i as f64) / 999.0;
            let p = sigmoid_clamped(rho / 1.0);
            let threshold = ((i % 10) as f64) / 10.0;
            buffer.push(CalibrationEntry {
                rho_eff: rho,
                uncertainty: 0.0,
                anchor_weight: 0.05,
                positive: p > threshold,
                importance_weight: 1.0,
                axis_data: vec![],
            });
        }

        // 1000 new entries generated with true κ = 5.0
        for i in 0..1_000 {
            let rho = -5.0 + 10.0 * (i as f64) / 999.0;
            let p = sigmoid_clamped(rho / 5.0);
            let threshold = ((i % 10) as f64) / 10.0;
            buffer.push(CalibrationEntry {
                rho_eff: rho,
                uncertainty: 0.0,
                anchor_weight: 0.05,
                positive: p > threshold,
                importance_weight: 1.0,
                axis_data: vec![],
            });
        }

        let config = PlattConfig {
            gamma_cal: 0.99,
            ..PlattConfig::default()
        };
        let result = refit_platt_calibration(&buffer, 1.0, 1.0, &config);

        assert!(result.sister_fitted);
        // Recency weighting should pull the fit toward the newer κ = 5.
        // The geometric midpoint is exp((ln1+ln5)/2) ≈ 2.24.  With
        // aggressive γ=0.99, the fit should clearly exceed it.
        assert!(
            result.kappa_sister > 3.0,
            "κ_sister={:.4} should be pulled toward 5.0 by recency, not 1.0",
            result.kappa_sister
        );
    }

    /// The probabilities the fitted constant produces mean what they say: sorted into
    /// deciles, every bin's mean predicted probability sits close to the rate at which
    /// its entries actually turned out adverse. Recovering the right constant is not
    /// the goal in itself — the goal is that a host reading a risk of one in five can
    /// act as though one in five is what it will be.
    ///
    /// ´claim:risk:probabilities-from-the-fitted-constant-match-observed-rates-decile-by-decile´
    /// ´test:unit:calibration-property-decile-bins´
    #[test]
    fn calibration_property_decile_bins() {
        // After fitting, bin predictions into deciles
        // and verify that the empirical positive rate in each bin
        // approximates the bin's mean predicted probability.
        let true_kappa = 2.0;
        let buffer = make_calibrated_entries(true_kappa, 2_000, 0.05);
        let config = PlattConfig::default();
        let result = refit_platt_calibration(&buffer, 1.0, 1.0, &config);
        assert!(result.sister_fitted);

        let fitted_kappa = result.kappa_sister;

        // Collect (predicted_probability, actual_positive) pairs.
        let mut pairs: Vec<(f64, bool)> = buffer
            .iter()
            .map(|e| {
                let p = sigmoid_clamped(e.rho_eff / fitted_kappa);
                (p, e.positive)
            })
            .collect();
        pairs.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());

        // Bin into 10 deciles.
        let bin_size = pairs.len() / 10;
        let mut max_error = 0.0_f64;

        for bin_idx in 0..10 {
            let start = bin_idx * bin_size;
            let end = if bin_idx == 9 { pairs.len() } else { start + bin_size };
            let bin = &pairs[start..end];

            let mean_predicted: f64 = bin.iter().map(|(p, _)| p).sum::<f64>() / bin.len() as f64;
            let empirical_rate: f64 = bin.iter().filter(|(_, pos)| *pos).count() as f64 / bin.len() as f64;

            let error = (mean_predicted - empirical_rate).abs();
            max_error = max_error.max(error);
        }

        // With 2000 entries and a correctly fitted κ, the worst-bin
        // calibration error should be modest. Allow 0.15 for the
        // deterministic threshold assignment (not truly random).
        assert!(max_error < 0.15, "worst decile calibration error {max_error:.4} exceeds 0.15");
    }
