    /// A buffer of zero scores is worse than uninformative — it is silent. Every
    /// candidate sharpness predicts a half for every row, so the cross-entropy is
    /// one constant across the whole search range, and what comes back is not a
    /// fit but the bound the iteration walks to while every comparison it makes
    /// is a tie. Two buffers sharing nothing else — different lengths, different
    /// base rates, different importance — return the same sharpness bit for bit,
    /// and the drift between them is not small but exactly nothing. That is what
    /// makes a drift bound applied to such a pair vacuous: it is not that the
    /// calibration held steady, it is that no calibration was performed, and the
    /// bound would pass at any width whatever. The neighbouring tests fit a
    /// fixture whose classes overlap for exactly this reason
    /// (´tab:assayer:harness-scenario-tolerances´).
    ///
    /// ´claim:risk:a-buffer-of-zero-scores-returns-the-same-bound-bit-for-bit-so-a-drift-bound-over-such-refits-is-vacuous´
    /// ´test:unit:flat-scores-leave-successive-refits-bit-identical´
    #[test]
    fn flat_scores_leave_successive_refits_bit_identical() {
        /// Builds a buffer whose every score is zero.
        fn flat(rows: usize, one_positive_in: usize, importance: f64) -> CalibrationBuffer {
            let mut buffer = CalibrationBuffer::new(rows);
            for row in 0..rows {
                buffer.push(CalibrationEntry {
                    rho_eff: 0.0,
                    uncertainty: 0.0,
                    anchor_weight: 0.05,
                    positive: row % one_positive_in == 0,
                    importance_weight: importance,
                    axis_data: vec![],
                });
            }
            buffer
        }

        let config = PlattConfig::default();
        let first = refit_platt_calibration(&flat(100, 2, 1.0), 1.0, 1.0, &config);
        let second = refit_platt_calibration(&flat(400, 4, 2.5), 1.0, 1.0, &config);

        assert!(
            first.sister_fitted && second.sister_fitted,
            "both buffers clear the sample floor"
        );

        // Bit-identical, not merely close: the two populations have no figure
        // in common, and the search never consulted them.
        crate::testing::assert_near(
            first.kappa_sister,
            second.kappa_sister,
            crate::testing::DEFAULT_TOLERANCES.bit_identical,
            "sharpness fitted to two unrelated buffers of zero scores",
        );

        // And what they agree on is the ceiling, short of it only by the half
        // of the final bracket the search stops on.
        assert!(
            config.kappa_max - first.kappa_sister < 0.01,
            "the returned sharpness {} should be the search's ceiling artefact, not an optimum",
            first.kappa_sister,
        );

        // So the declared drift bound admits this pair while deciding nothing.
        assert!(
            (first.kappa_sister.ln() - second.kappa_sister.ln()).abs() <= crate::testing::DEFAULT_TOLERANCES.platt_log_sharpness,
            "the vacuity is the point: the bound passes because the difference is identically zero",
        );
    }

    /// Classes whose scores genuinely overlap put the fit at an interior optimum
    /// rather than against a search bound: the overlap ladder's fitted constant
    /// lands on the root of the stationarity condition its own counts imply, and
    /// sits some four units of log-κ clear of either end of the search range. The
    /// preceding test is the contrast that gives this one its point — a buffer
    /// whose scores carry no information leaves the search resting on a bound,
    /// where the returned constant is an artefact of how the iteration breaks a
    /// tie and no later assertion about it can discriminate anything. An interior
    /// optimum is what makes the fitted constant a statement about the data, and
    /// it is the precondition the search's own unimodality argument rests on.
    ///
    /// ´claim:risk:overlapping-score-classes-put-the-fit-at-an-interior-optimum-rather-than-against-a-search-bound´
    /// ´test:unit:overlap-ladder-fit-lands-at-the-interior-optimum´
    #[test]
    fn overlap_ladder_fit_lands_at_the_interior_optimum() {
        let buffer = overlap_ladder_buffer(1.0, 2);
        let config = overlap_ladder_config();

        let result = refit_platt_calibration(&buffer, 1.0, 1.0, &config);

        assert!(result.sister_fitted, "the ladder clears the sister regime's sample floor");

        // The search resolves log-κ only to its own golden tolerance, so the
        // constant it returns sits within about half that of the hand-derived
        // root — the band below is that resolution with room to spare, and is
        // far tighter than the distance to either bound.
        assert!(
            (result.kappa_sister - OVERLAP_LADDER_KAPPA).abs() < 1e-3,
            "fitted κ_sister={} should sit on the stationarity root {OVERLAP_LADDER_KAPPA}",
            result.kappa_sister,
        );

        // Interior by a margin, stated in the coordinate the search works in.
        let margin = (result.kappa_sister.ln() - config.kappa_min.ln()).min(config.kappa_max.ln() - result.kappa_sister.ln());
        assert!(
            margin > 3.0,
            "fitted κ_sister={} should stand clear of both search bounds; margin in log-κ was {margin}",
            result.kappa_sister,
        );
    }

    /// Multiplying every score by a factor multiplies the fitted constant by that
    /// same factor, which is what makes the declared drift bound a two-sided
    /// assertion: a four-percent perturbation of the scores moves the constant
    /// and stays inside the bound, while a ten-percent one moves it past and the
    /// bound rejects it. Both halves are asserted because a bound that only ever
    /// sees movement it admits is indistinguishable from a bound that admits
    /// everything — the rejecting case is what shows the figure is deciding
    /// something (´tab:assayer:harness-scenario-tolerances´).
    ///
    /// ´claim:risk:scaling-every-score-scales-the-fitted-constant-alike-so-the-drift-bound-admits-the-small-move-and-rejects-the-large´
    /// ´test:unit:overlap-ladder-drift-bound-admits-and-rejects´
    #[test]
    fn overlap_ladder_drift_bound_admits_and_rejects() {
        /// The perturbation the bound is meant to admit.
        const SMALL: f64 = 1.04;
        /// The perturbation the bound is meant to reject.
        const LARGE: f64 = 1.10;

        let config = overlap_ladder_config();
        let fit = |scale: f64| refit_platt_calibration(&overlap_ladder_buffer(scale, 2), 1.0, 1.0, &config).kappa_sister;

        let base = fit(1.0);
        let small = fit(SMALL);
        let large = fit(LARGE);

        // The proportionality itself, before either bound is consulted.
        assert!(
            (small - SMALL * base).abs() < 1e-3,
            "a {SMALL}× score scaling should carry κ from {base} to {}, but the fit gave {small}",
            SMALL * base,
        );
        assert!(
            (large - LARGE * base).abs() < 1e-3,
            "a {LARGE}× score scaling should carry κ from {base} to {}, but the fit gave {large}",
            LARGE * base,
        );

        // The comparison is in log-sharpness, so what the bound sees is the
        // proportion the sharpness moved by and not the distance it moved.
        // That is what makes this pair of stimuli a test of the bound rather
        // than of the fixture: a scaling by a factor is the same proportional
        // move at every sharpness, so the same four-percent and ten-percent
        // perturbations would be admitted and rejected at any optimum, and not
        // only near this ladder's own (´tab:assayer:harness-scenario-tolerances´).
        let bound = crate::testing::DEFAULT_TOLERANCES.platt_log_sharpness;

        // Green: the perturbed refit moved, and moved by less than the bound.
        let admitted = (small.ln() - base.ln()).abs();
        assert!(
            admitted > 0.0,
            "the perturbed refit must actually move, else the bound decides nothing",
        );
        assert!(
            admitted <= bound,
            "a {SMALL}× perturbation should stay inside the declared drift bound: κ went {base} → {small} \
             (|Δ ln κ| = {admitted}, bound {bound})",
        );

        // Red: the deliberate violation is caught.
        let rejected = (large.ln() - base.ln()).abs();
        assert!(
            rejected > bound,
            "a {LARGE}× perturbation should breach the declared drift bound: κ went {base} → {large} \
             (|Δ ln κ| = {rejected}, bound {bound})",
        );
    }

    /// A fitted constant never leaves the configured search interval, even when the
    /// data was generated by a constant near its lower end. The search brackets the
