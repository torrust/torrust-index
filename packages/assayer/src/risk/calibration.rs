    /// Helper: generate entries from a sigmoid model with known κ.
    ///
    /// Uses deterministic assignment: entry i is positive iff
    /// `σ`(`ρ_i` / `κ_true`) > `threshold_i`, where `threshold_i` is evenly spaced.
    fn make_calibrated_entries(true_kappa: f64, n: usize, anchor_weight: f64) -> CalibrationBuffer {
        let mut buffer = CalibrationBuffer::new(n);
        for i in 0..n {
            // Spread ρ values over a reasonable range
            let rho_eff = -5.0 + 10.0 * (i as f64) / (n as f64 - 1.0).max(1.0);
            let p_true = sigmoid_clamped(rho_eff / true_kappa);
            // Deterministic threshold: entry i is positive if p_true > (i % 10) / 10
            let threshold = ((i % 10) as f64) / 10.0;
            let is_positive = p_true > threshold;

            buffer.push(CalibrationEntry {
                rho_eff,
                uncertainty: 0.0,
                anchor_weight,
                positive: is_positive,
                importance_weight: 1.0,
                axis_data: vec![],
            });
        }
        buffer
    }

    /// The rungs of the overlap ladder: `(score, rows, positive rows)`.
    ///
    /// Eight rows stand at each of five scores and every rung carries both
    /// outcomes — one positive at the bottom, seven at the top, four in the
    /// middle — so the two classes overlap across the whole range instead of
    /// separating at some cut. The positive counts are antisymmetric about the
    /// middle rung, which balances a block at twenty positives to twenty
    /// negatives and drops the zero-score rung out of the stationarity
    /// condition below.
    const OVERLAP_LADDER: [(f64, usize, usize); 5] = [(-4.0, 8, 1), (-2.0, 8, 2), (0.0, 8, 4), (2.0, 8, 6), (4.0, 8, 7)];

    /// The κ minimising the overlap ladder's unweighted cross-entropy.
    ///
    /// This is not a reading taken from the search. Writing `u = 1/κ`, the
    /// derivative of the loss is `Σ_ℓ ρ_ℓ (N_ℓ σ(ρ_ℓ u) − n⁺_ℓ)`; the
    /// zero-score rung contributes nothing and the antisymmetric pairs
    /// collapse it to `2σ(4u) + σ(2u) = 5/2`, whose root is
    /// `u = 0.506_000_543_503_559_1`. This constant is that root's reciprocal.
    /// The second derivative is `Σ_ℓ ρ_ℓ² N_ℓ p_ℓ(1 − p_ℓ)`, strictly positive
    /// wherever any score is non-zero, so the loss is strictly convex in `u`
    /// and the root is the unique minimum rather than one stationary point
    /// among several.
    const OVERLAP_LADDER_KAPPA: f64 = 1.976_282_462_220_253;

    /// Builds a buffer holding `blocks` repetitions of the overlap ladder,
    /// every score multiplied by `scale`.
    ///
    /// The objective reads the scores only through the product `ρ/κ`, so
    /// multiplying every score by `s` moves the minimising κ to exactly
    /// `s · κ*`. That is how the drift scenario below displaces the fit by an
    /// amount settled in advance rather than one discovered by running it.
    ///
    /// Every row carries unit importance and one shared anchor weight, so the
    /// weights the fit computes differ only by the recency discount; with that
    /// discount switched off the per-row weights are one common factor, which
    /// scales the loss without moving its argument. Repeating the block
    /// therefore leaves the minimising κ where a single block put it.
    fn overlap_ladder_buffer(scale: f64, blocks: usize) -> CalibrationBuffer {
        let rows_per_block: usize = OVERLAP_LADDER.iter().map(|&(_, rows, _)| rows).sum();
        let mut buffer = CalibrationBuffer::new(blocks * rows_per_block);
        for _ in 0..blocks {
            for (rho, rows, positives) in OVERLAP_LADDER {
                for row in 0..rows {
                    buffer.push(CalibrationEntry {
                        rho_eff: rho * scale,
                        uncertainty: 0.0,
                        anchor_weight: 0.05,
                        positive: row < positives,
                        importance_weight: 1.0,
                        axis_data: vec![],
                    });
                }
            }
        }
        buffer
    }

    /// The configuration the ladder is fitted under: the shipped one with the
    /// recency discount switched off.
    ///
    /// Recency is what makes the fit track a moving population, and another
    /// test in this module holds it to that. Here it would only correlate the
    /// row weights with the order the rungs happen to be laid down in, which
    /// would displace the minimum away from the root the ladder's counts
    /// imply and leave the expectation unrecomputable by hand. At `γ_cal = 1`
    /// the objective is the plain unweighted cross-entropy of that root.
    fn overlap_ladder_config() -> PlattConfig {
        PlattConfig {
            gamma_cal: 1.0,
            ..PlattConfig::default()
        }
    }

