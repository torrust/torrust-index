/// Sigmoid with output clamping to prevent log(0).
///
/// Delegates to [`crate::numerics::stable_sigmoid`] for the core
/// two-branch computation, then clamps the output to `[ε, 1−ε]`
/// for log-loss stability.
///
/// The search's objective is the fit's second phase (´alg:platt:fitting´).
/// The package mandates one sigmoid definition and multiple imports of it —
/// this thin wrapper adds only the clamp.
fn sigmoid_clamped(x: f64) -> f64 {
    /// Clamping epsilon to prevent log(0).
    const EPS: f64 = 1e-15;

    crate::numerics::stable_sigmoid(x).clamp(EPS, 1.0 - EPS)
}

