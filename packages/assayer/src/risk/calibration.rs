/// Pre-computed weights for a single buffer entry, used during fitting.
struct PrecomputedEntry {
    /// The raw blended risk score `ρ̂_eff`.
    rho: f64,
    /// Whether this was a positive outcome.
    positive: bool,
    /// Combined weight for the sister regime.
    sister_weight: f64,
    /// Combined weight for the anchor regime.
    anchor_weight: f64,
}

/// Selects which regime to fit or count.
#[derive(Clone, Copy, Debug)]
enum RegimeSelector {
    /// Sister-dominated regime (w < 0.3).
    Sister,
    /// Anchor-dominated regime (w ≥ 0.3).
    Anchor,
}

/// Effective sample counts for a single regime.
#[derive(Clone, Copy, Debug)]
struct EffectiveCounts {
    /// Total weighted count.
    total: f64,
    /// Weighted positive count.
    positive: f64,
    /// Weighted negative count.
    negative: f64,
}

impl EffectiveCounts {
    /// Returns `true` if minimum sample requirements are met.
    fn meets_minimums(&self, config: &PlattConfig) -> bool {
        self.total >= f64::from(config.n_cal_min)
            && self.positive >= f64::from(config.n_cal_pos)
            && self.negative >= f64::from(config.n_cal_neg)
    }
}

