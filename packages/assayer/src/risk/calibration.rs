    /// The sample floor reads the undiscounted weighted count — the same
    /// quantity the cheap pre-check computes — so an anchor regime whose
    /// evidence is old but sufficient is fitted rather than abandoned. Under
    /// a recency-discounted floor the same buffer sits in a trap: the
    /// pre-check keeps saying refit, the fit keeps refusing, the refit
    /// bookkeeping never advances, and a full search runs on every label.
    /// Recency belongs to the objective, which tracks the current score
    /// distribution; the floor is an evidence census and takes no discount.
    ///
    /// ´claim:risk:the-sample-floor-reads-the-undiscounted-weighted-count-the-pre-check-computes´
    /// ´test:unit:sample-floor-reads-undiscounted-count´
    #[test]
    fn sample_floor_reads_undiscounted_count() {
        let config = PlattConfig::default();
        let mut buffer = CalibrationBuffer::new(2_000);

        // 31 anchor-regime records first, i.e. oldest, with both outcomes
        // present. With the sister entries' small anchor share the
        // undiscounted anchor census is ≈ 38, above n_cal_min = 30.
        for i in 0..31 {
            buffer.push(CalibrationEntry {
                rho_eff: f64::from(i).mul_add(0.1, -1.5),
                uncertainty: 0.0,
                anchor_weight: 0.95,
                positive: i % 4 == 0,
                importance_weight: 1.0,
                axis_data: vec![],
            });
        }
        // 1,969 newer sister-regime records push the anchor block ~2,000
        // ranks back: at γ_cal = 0.9998 its recency factor is ≈ 0.67, so a
        // discounted census would read ≈ 27 and refuse the floor.
        for i in 0..1_969 {
            buffer.push(CalibrationEntry {
                rho_eff: f64::from(i % 40).mul_add(0.05, -1.0),
                uncertainty: 0.0,
                anchor_weight: 0.02,
                positive: i % 5 == 0,
                importance_weight: 1.0,
                axis_data: vec![],
            });
        }

        // The pre-check and the floor read the same census.
        assert!(buffer.has_sufficient_anchor_samples(&config));

        let result = refit_platt_calibration(&buffer, 1.0, 1.0, &config);
        assert!(
            result.anchor_fitted,
            "anchor floor must read the undiscounted count, not the recency-discounted one"
        );

        // Independent recomputation of the undiscounted census: the anchor
        // block plus the sister entries' small anchor share. Discounting the
        // old anchor block by its ≈0.67 recency would read below the floor.
        let expected = 31.0_f64.mul_add(
            crate::numerics::regime_transition(0.95),
            1_969.0 * crate::numerics::regime_transition(0.02),
        );
        assert!(
            (result.anchor_effective_samples - expected).abs() < 1e-9,
            "reported anchor samples should be the undiscounted census {expected}, got {}",
            result.anchor_effective_samples
        );
    }

