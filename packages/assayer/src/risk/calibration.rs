    /// Every iteration of the search strictly narrows the bracket, on real
    /// weighted data and in both of the branches the comparison can take. Because the
    /// interval only ever shrinks, the loop's progress toward its tolerance is
    /// guaranteed by the step itself rather than by the iteration cap catching a
    /// search that had stalled.
    ///
    /// ´claim:risk:every-golden-section-iteration-strictly-narrows-the-bracket´
    /// ´test:unit:golden-section-monotonicity´
    #[test]
    fn golden_section_monotonicity() {
        // The interval (b − a) must shrink every iteration.
        let buffer = make_calibrated_entries(2.0, 500, 0.05);
        let config = PlattConfig::default();
        let precomputed = precompute_weights(&buffer, config.gamma_cal);

        let log_lo = config.kappa_min.ln();
        let log_hi = config.kappa_max.ln();
        let inv_phi = 2.0 / (1.0 + 5.0_f64.sqrt());

        let loss_at = |log_kappa: f64| -> f64 { regime_loss(&precomputed, RegimeSelector::Sister, log_kappa.exp()) };

        let mut a = log_lo;
        let mut b = log_hi;
        let mut x1 = b - inv_phi * (b - a);
        let mut x2 = a + inv_phi * (b - a);
        let mut f1 = loss_at(x1);
        let mut f2 = loss_at(x2);
        let mut prev_width = b - a;

        for _ in 0..config.max_golden_iterations {
            if (b - a).abs() < config.golden_tolerance {
                break;
            }
            if f1 < f2 {
                b = x2;
                x2 = x1;
                f2 = f1;
                x1 = b - inv_phi * (b - a);
                f1 = loss_at(x1);
            } else {
                a = x1;
                x1 = x2;
                f1 = f2;
                x2 = a + inv_phi * (b - a);
                f2 = loss_at(x2);
            }
            let width = b - a;
            assert!(width < prev_width, "interval must shrink: {prev_width:.6} → {width:.6}");
            prev_width = width;
        }
    }

