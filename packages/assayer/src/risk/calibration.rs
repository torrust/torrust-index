/// Performs a full Platt calibration refit.
///
/// Pure function: buffer + old κ values + config → `PlattRefitResult`.
/// No side effects — the caller applies the result to the working copy,
/// convergence tracker, and drift accumulators.
///
/// # Three phases
///
/// 1. **Pre-scan:** compute per-entry combined weights for both regimes.
/// 2. **Per-regime golden section:** fit each eligible regime.
/// 3. **Post-fit:** compute `δ_cal` and assemble result.
///
/// # Cross-References
///
/// - (´alg:platt:fitting´) — the three-phase fit this implements
#[must_use]
#[cfg(test)]
pub fn refit_platt_calibration(
    buffer: &CalibrationBuffer,
    old_kappa_sister: f64,
    old_kappa_anchor: f64,
    config: &PlattConfig,
) -> PlattRefitResult {
    let monitoring = crate::config::types::MonitoringConfig::default();
    refit_platt_calibration_with_monitoring(buffer, old_kappa_sister, old_kappa_anchor, config, &monitoring)
}

/// Performs a Platt refit with host-configured discrimination thresholds.
#[must_use]
pub fn refit_platt_calibration_with_monitoring(
    buffer: &CalibrationBuffer,
    old_kappa_sister: f64,
    old_kappa_anchor: f64,
    config: &PlattConfig,
    monitoring: &crate::config::types::MonitoringConfig,
) -> PlattRefitResult {
    if buffer.is_empty() {
        return PlattRefitResult {
            kappa_sister: old_kappa_sister,
            kappa_anchor: old_kappa_anchor,
            delta_cal: 0.0,
            sister_fitted: false,
            anchor_fitted: false,
            sister_effective_samples: 0.0,
            anchor_effective_samples: 0.0,
            discrimination: None,
        };
    }

    // ── Phase 1: Pre-scan ───────────────────────────────────────────
    let precomputed = precompute_weights(buffer, config.gamma_cal);

    // The floor is read against the undiscounted weighted counts
    // (´constr:platt:buffer´); the recency factor belongs to the
    // objective alone (´def:platt:objective´).
    let sister_counts = effective_sample_counts(buffer, RegimeSelector::Sister);
    let anchor_counts = effective_sample_counts(buffer, RegimeSelector::Anchor);

    // ── Phase 2: Per-regime golden section ──────────────────────────
    let sister_result = if sister_counts.meets_minimums(config) {
        Some(fit_single_regime(&precomputed, RegimeSelector::Sister, config))
    } else {
        None
    };

    let anchor_result = if anchor_counts.meets_minimums(config) {
        Some(fit_single_regime(&precomputed, RegimeSelector::Anchor, config))
    } else {
        None
    };

    // ── Phase 3: Post-fit assembly ──────────────────────────────────
    let kappa_sister = sister_result.unwrap_or(old_kappa_sister);
    let kappa_anchor = anchor_result.unwrap_or(old_kappa_anchor);

    let delta_sister = if sister_result.is_some() {
        (kappa_sister.ln() - old_kappa_sister.ln()).abs()
    } else {
        0.0
    };
    let delta_anchor = if anchor_result.is_some() {
        (kappa_anchor.ln() - old_kappa_anchor.ln()).abs()
    } else {
        0.0
    };

    // ── Phase 3b: Discrimination metrics (´dec:health:cached-discrimination´), at the post-fit
    // parameters so the coverage residuals are formed at the current
    // regime's calibration (´alg:monitoring:empirical-coverage´). The
    // AUC family reads only the rows and is unaffected by the move
    // from the pre-fit phase.
    let cal_rows: Vec<_> = buffer
        .iter()
        .map(|e| (e.rho_eff, e.positive, e.anchor_weight, e.uncertainty, e.axis_data.clone()))
        .collect();
    let discrimination = {
        let metrics = crate::health::compute_discrimination_metrics_with_monitoring(
            &cal_rows,
            kappa_sister,
            kappa_anchor,
            config.n_cal_min as usize,
            monitoring,
        );
        // Only keep if at least one AUC was computed
        if metrics.auc_aggregate.is_some() {
            Some(metrics)
        } else {
            None
        }
    };

    PlattRefitResult {
        kappa_sister,
        kappa_anchor,
        delta_cal: delta_sister.max(delta_anchor),
        sister_fitted: sister_result.is_some(),
        anchor_fitted: anchor_result.is_some(),
        sister_effective_samples: sister_counts.total,
        anchor_effective_samples: anchor_counts.total,
        discrimination,
    }
}

// ═══════════════════════════════════════════════════════════════════════════════
// Phase 1: Pre-scan
// ═══════════════════════════════════════════════════════════════════════════════

/// Pre-computes per-entry combined weights for both regimes.
///
/// Iterates newest-first for numerically stable recency weighting.
/// Newest entry gets recency = 1.0; each step back multiplies by `γ_cal`.
///
/// The pre-scan is the fit's first phase (´alg:platt:fitting´).
fn precompute_weights(buffer: &CalibrationBuffer, gamma_cal: f64) -> Vec<PrecomputedEntry> {
    let n = buffer.len();
    let mut result = Vec::with_capacity(n);

    let mut recency = 1.0;
    for entry in buffer.iter().rev() {
        let g = regime_transition(entry.anchor_weight);

        result.push(PrecomputedEntry {
            rho: entry.rho_eff,
            positive: entry.positive,
            sister_weight: (1.0 - g) * entry.importance_weight * recency,
            anchor_weight: g * entry.importance_weight * recency,
        });

        recency *= gamma_cal;
    }

    // Reverse to restore oldest-first order (matches buffer).
    result.reverse();
    result
}

/// Computes a regime's effective sample counts: each record's regime
/// share times its importance weight, with no recency discount
/// (´constr:platt:buffer´).
fn effective_sample_counts(buffer: &CalibrationBuffer, regime: RegimeSelector) -> EffectiveCounts {
    let mut total = 0.0;
    let mut positive = 0.0;

    for entry in buffer.iter() {
        let g = regime_transition(entry.anchor_weight);
        let share = match regime {
            RegimeSelector::Sister => 1.0 - g,
            RegimeSelector::Anchor => g,
        };
        let w = share * entry.importance_weight;
        total += w;
        if entry.positive {
            positive += w;
        }
    }

    EffectiveCounts {
        total,
        positive,
        negative: total - positive,
    }
}

