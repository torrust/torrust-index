    /// The recency discount is anchored at the newest entry, which carries full
    /// weight, with each older one worth a fixed fraction more of the discount — so
    /// the newest entry in a buffer outweighs the oldest. Anchoring at the newest
    /// rather than the oldest keeps the weights bounded by one however long the
    /// buffer has been running.
    ///
    /// ´claim:risk:recency-weighting-gives-the-newest-entry-full-weight-and-discounts-each-older-one´
    /// ´test:unit:precompute-newest-first-recency´
