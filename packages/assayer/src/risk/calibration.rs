/// One entry in the calibration buffer.
///
/// Written at label time (step 14) from `PendingAssessment.risk_basis`
/// and the label's outcome. Consumed by the Platt fitting algorithm
/// (´alg:platt:fitting´).
///
/// # Cross-References
///
/// - (´constr:platt:buffer´) — the buffer this entry is written into and the
///   effective sample counts read from it
/// - (´dec:health:cached-discrimination´) — why the per-axis rows are carried
///   here and read once at refit
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct CalibrationEntry {
    /// Blended risk score `ρ̂_eff` at assessment time.
    pub rho_eff: f64,
    /// Probability-space uncertainty `σ_p̂` at assessment time — the
    /// denominator of the standardised residual empirical coverage
    /// computes per row (´alg:monitoring:empirical-coverage´).
    ///
    /// As reported, so as tempered: the figure recorded here is evidence-only
    /// along that request's own direction, widened by whatever share of the
    /// precision behind it the models' floors were holding up
    /// (´dec:risk:evidence-only-uncertainty´). The refit therefore sees wider
    /// intervals from degraded models and inflates less on their account,
    /// which is the two corrections agreeing rather than double counting: the
    /// share corrects what the model can know about itself, and the refit
    /// corrects what it cannot.
    pub uncertainty: f64,
    /// Anchor blend weight `w` at assessment time.
    pub anchor_weight: f64,
    /// Binary outcome: `true` if valence > 0.
    pub positive: bool,
    /// Importance weight at label time (from step 8).
    // TODO(2026-05-21) ´todo:code:add-label-index-u64-once-the´: Add `label_index: u64` once the
    // model-owner label counter is threaded into calibration entries by the
    // label path (´dec:ordering:label-function´).
    pub importance_weight: f64,
    /// Per-axis (`axis_id`, predicted, actual) pairs for discrimination
    /// metrics (´dec:health:cached-discrimination´).
    /// Empty when no outcome axes exist.
    pub axis_data: Vec<(crate::types::OutcomeAxisId, f64, f64)>,
}

/// Fixed-capacity circular buffer of calibration entries.
///
/// Entries are ordered by insertion time (oldest at front, newest
/// at back). When at capacity, the oldest entry is evicted on push.
///
/// The capacity and eviction are the buffer's own (´constr:platt:buffer´).
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct CalibrationBuffer {
    /// The entries, oldest at front.
    entries: VecDeque<CalibrationEntry>,
    /// Maximum capacity.
    capacity: usize,
}

impl CalibrationBuffer {
    /// Creates a new empty buffer with the given capacity.
    #[must_use]
    pub fn new(capacity: usize) -> Self {
        Self {
            entries: VecDeque::with_capacity(capacity),
            capacity,
        }
    }

    /// Pushes a new entry, evicting the oldest if at capacity.
    pub fn push(&mut self, entry: CalibrationEntry) {
        if self.entries.len() >= self.capacity {
            self.entries.pop_front();
        }
        self.entries.push_back(entry);
    }

    /// Returns the number of entries in the buffer.
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Returns `true` if the buffer is empty.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// Truncates the buffer to at most `len` entries, removing from the back.
    ///
    /// Used for checkpoint/restore: reverts the buffer to a prior state.
    pub fn truncate(&mut self, len: usize) {
        self.entries.truncate(len);
    }

    /// Returns a double-ended iterator over the entries (oldest first).
    pub fn iter(&self) -> impl DoubleEndedIterator<Item = &CalibrationEntry> {
        self.entries.iter()
    }

    /// Estimates whether the anchor regime has sufficient weighted samples.
    ///
    /// Lightweight O(n) scan used by the anchor-reactivation trigger
    /// (´tab:platt:refit-cadence´) to avoid triggering a full refit when the anchor
    /// regime cannot contribute. It computes the same undiscounted
    /// weighted count the fit's own sample floor reads
    /// (´constr:platt:buffer´), so the scan and the floor agree.
    #[must_use]
    pub fn has_sufficient_anchor_samples(&self, config: &PlattConfig) -> bool {
        let mut total = 0.0;
        let mut positive = 0.0;

        for entry in &self.entries {
            let g = regime_transition(entry.anchor_weight);
            let w = g * entry.importance_weight;
            total += w;
            if entry.positive {
                positive += w;
            }
        }

        let negative = total - positive;
        total >= f64::from(config.n_cal_min) && positive >= f64::from(config.n_cal_pos) && negative >= f64::from(config.n_cal_neg)
    }

    /// Projects the buffer into an immutable snapshot for the published
    /// `ModelSnapshot`.
    ///
    /// The regime counts are weighted sample counts: each record enters
    /// the sister count at `(1 − g(w)) · w_imp` and the anchor count at
    /// `g(w) · w_imp`, so the published quantities are the effective
    /// sample counts the sample floor is read against
    /// (´constr:platt:buffer´).
    ///
    /// # Cross-References
    ///
    /// - (´dec:calibration:per-regime-search´) — the minimum-sample floor these
    ///   published counts are read against
    #[must_use]
    pub fn to_snapshot(&self) -> crate::snapshot::published::CalibrationBufferSnapshot {
        let mut sister = 0.0_f64;
        let mut anchor = 0.0_f64;
        for entry in &self.entries {
            let g = regime_transition(entry.anchor_weight);
            sister = (1.0 - g).mul_add(entry.importance_weight, sister);
            anchor = g.mul_add(entry.importance_weight, anchor);
        }
        crate::snapshot::published::CalibrationBufferSnapshot {
            total_entries: self.entries.len(),
            sister_regime_records: sister,
            anchor_regime_records: anchor,
        }
    }
}

impl Default for CalibrationBuffer {
    fn default() -> Self {
        Self::new(2_000)
    }
}

