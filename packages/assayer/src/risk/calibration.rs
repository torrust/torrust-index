//! # Test index
//!
//! | Test | Area | Claim |
//! |------|------|-------|
//! | [`empty_buffer_returns_old_kappa`] | risk | A refit with nothing to learn from returns the calibration it was given, unmoved: both constants come back as they went in, the reported movement is zero, neither regime is marked fitted and both effective sample counts are empty. A refit triggered before any labels have arrived is a no-op rather than a reset to whatever the fit's default would be. |
//! | [`synthetic_convergence_kappa_2`] | risk | Given outcomes generated by a known calibration constant, the fit recovers that constant from a starting point well away from it. The search is therefore doing statistics rather than tracking its own initialisation: it finds the scaling that the data actually implies. |
//! | [`regime_separation`] | risk | One buffer holding entries from both regimes, each generated with its own calibration constant, yields two fits that both succeed and end up clearly apart. The regimes are fitted independently, so a sister-dominated score and an anchor-dominated one are not forced to share a scaling that suits neither. |
//! | [`minimum_sample_guard`] | risk | Plenty of entries is not the same as enough of each outcome. A regime with fifty negatives but only two positives is left unfitted and keeps its previous constant, because the minimum is enforced on the positive and negative counts separately. Fitting a sigmoid to data that is one-sided would push the constant to a bound on the strength of two labels. |
//! | [`stub_valued_entries_converge`] | risk | When every score in the buffer is identical the loss surface carries no information about the scaling, and the search still terminates with a finite, positive constant inside its bounds — it drifts to a boundary rather than diverging or returning something unusable. A stub-valued or saturated period leaves calibration harmlessly inert instead of breaking it. |
//! | [`flat_scores_leave_successive_refits_bit_identical`] | risk | A buffer of zero scores is worse than uninformative — it is silent. Every candidate sharpness predicts a half for every row, so the cross-entropy is one constant across the whole search range, and what comes back is not a fit but the bound the iteration walks to while every comparison it makes is a tie. Two buffers sharing nothing else — different lengths, different base rates, different importance — return the same sharpness bit for bit, and the drift between them is not small but exactly nothing. That is what makes a drift bound applied to such a pair vacuous: it is not that the calibration held steady, it is that no calibration was performed, and the bound would pass at any width whatever. The neighbouring tests fit a fixture whose classes overlap for exactly this reason (´tab:assayer:harness-scenario-tolerances´). |
//! | [`overlap_ladder_fit_lands_at_the_interior_optimum`] | risk | Classes whose scores genuinely overlap put the fit at an interior optimum rather than against a search bound: the overlap ladder's fitted constant lands on the root of the stationarity condition its own counts imply, and sits some four units of log-κ clear of either end of the search range. The preceding test is the contrast that gives this one its point — a buffer whose scores carry no information leaves the search resting on a bound, where the returned constant is an artefact of how the iteration breaks a tie and no later assertion about it can discriminate anything. An interior optimum is what makes the fitted constant a statement about the data, and it is the precondition the search's own unimodality argument rests on. |
//! | [`overlap_ladder_drift_bound_admits_and_rejects`] | risk | Multiplying every score by a factor multiplies the fitted constant by that same factor, which is what makes the declared drift bound a two-sided assertion: a four-percent perturbation of the scores moves the constant and stays inside the bound, while a ten-percent one moves it past and the bound rejects it. Both halves are asserted because a bound that only ever sees movement it admits is indistinguishable from a bound that admits everything — the rejecting case is what shows the figure is deciding something (´tab:assayer:harness-scenario-tolerances´). |
//! | [`search_within_bounds`] | risk | A fitted constant never leaves the configured search interval, even when the data was generated by a constant near its lower end. The search brackets the whole of log-space between the two bounds and can only ever narrow inwards, so the operator's limits are a guarantee about the output and not merely a starting hint. |
//! | [`no_nan_in_loss`] | risk | The cross-entropy stays finite across the whole search range even for scores far outside anything the model would ordinarily produce, including a confidently wrong one. The loss takes a logarithm of the predicted probability, so a single saturated score would otherwise contribute an infinity and make every candidate constant look equally bad. |
//! | [`sigmoid_clamped_never_zero_or_one`] | risk | This is why: the calibration sigmoid is held strictly inside the unit interval, at scores of a thousand in either direction as much as at zero. Neither endpoint is ever returned, so the logarithm the loss takes of it and of its complement always has an argument. |
//! | [`precompute_newest_first_recency`] | risk | The recency discount is anchored at the newest entry, which carries full weight, with each older one worth a fixed fraction more of the discount — so the newest entry in a buffer outweighs the oldest. Anchoring at the newest rather than the oldest keeps the weights bounded by one however long the buffer has been running. |
//! | [`buffer_push_evicts_oldest`] | risk | The calibration buffer is bounded and drops from the front: pushing beyond capacity leaves exactly the most recent entries, in order. Memory is therefore fixed however long the instance runs, and what is sacrificed for that is always the oldest evidence — the evidence recency weighting was already discounting most heavily. |
//! | [`delta_cal_log_space`] | risk | How far the calibration moved is measured as the absolute difference of the logarithms, not of the constants themselves. Movement is therefore relative: a step from one to two counts the same as a step from ten to twenty, which is what a downstream threshold on "the calibration has shifted" needs, since the constant is a scaling. |
//! | [`golden_section_terminates`] | risk | A tolerance so tight that floating-point arithmetic can never satisfy it does not hang the search: the iteration cap ends it and a finite constant comes back. The refit runs on the model owner's thread, so a convergence criterion that cannot be met has to cost a bounded number of iterations rather than the instance. |
//! | [`anchor_refit_label_index_updated`] | risk | A refit that actually fitted the anchor regime is recorded against the label count at which it happened, moving the tracker's stamp off its initial zero. The reactivation trigger measures how long the anchor has gone unfitted from that stamp, so a refit that succeeded but was not recorded would make the anchor look permanently overdue. |
//! | [`regime_transition_shared_with_blend`] | risk | Calibration and blending divide the regimes with one shared transition function, agreeing exactly across the weight range rather than approximately. Two copies that drifted apart would mean an entity was blended as one regime and calibrated as another, and the mismatch would show up only as a mis-calibrated probability with nothing pointing at its cause. |
//! | [`delta_cal_exceeds_threshold`] | risk | The reported movement is large enough to be acted on when the calibration genuinely moves: data generated by a constant three times the one in force produces movement past the default drift-reset threshold. The threshold is therefore reachable by an ordinary recalibration, not a bar only a pathological one could clear. |
//! | [`has_sufficient_anchor_samples_true`] | risk | The cheap pre-check admits a buffer that a real fit would accept: a hundred anchor-dominated entries carrying both outcomes clears the minimums. This scan is what decides whether a reactivation refit is worth running at all, so it has to say yes when the anchor really could be fitted. |
//! | [`has_sufficient_anchor_samples_false`] | risk | The check counts each entry by its regime rather than by its existence, so fifty sister-dominated entries contribute almost nothing toward the anchor's minimums and the answer is no. Counting entries outright would report a busy sister-regime instance as having anchor evidence it has never gathered. |
//! | [`sample_floor_reads_undiscounted_count`] | risk | The sample floor reads the undiscounted weighted count — the same quantity the cheap pre-check computes — so an anchor regime whose evidence is old but sufficient is fitted rather than abandoned. Under a recency-discounted floor the same buffer sits in a trap: the pre-check keeps saying refit, the fit keeps refusing, the refit bookkeeping never advances, and a full search runs on every label. Recency belongs to the objective, which tracks the current score distribution; the floor is an evidence census and takes no discount. |
//! | [`snapshot_counts_weighted_below_threshold`] | risk | The published regime counts are weighted samples, not a census against a hard threshold: a buffer whose entries all sit just below the old 0.3 split still reports substantial anchor evidence, because each record enters the anchor count at its transition share times its importance weight. A threshold tally would have reported zero anchor evidence here — and, through the risk basis, no anchor maturity — while the fit's own floor read a weighted count near half the buffer. |
//! | [`sigmoid_clamped_matches_stable_sigmoid`] | risk | The calibration sigmoid is the crate's shared stable sigmoid with a clamp applied, matching it exactly wherever the clamp is not binding. There is one definition of the logistic curve in the package and calibration adds only the log-loss guard on top — a second implementation would eventually disagree with the one deciding probabilities on the assessment path. |
//! | [`golden_section_monotonicity`] | risk | Every iteration of the search strictly narrows the bracket, on real weighted data and in both of the branches the comparison can take. Because the interval only ever shrinks, the loop's progress toward its tolerance is guaranteed by the step itself rather than by the iteration cap catching a search that had stalled. |
//! | [`boundary_convergence_all_positive`] | risk | Data that is adverse wherever the score is high and benign where it is very low drives the constant toward the steep end of its range, because the sharpest sigmoid is the one that best reproduces such a clean separation. The search leaning on a bound is the correct answer for near-separable data rather than a failure to converge. |
//! | [`recency_weighting_dominance`] | risk | When the older and newer halves of the buffer were generated by different calibrations, the fit follows the newer one — landing well past the geometric midpoint the two halves would give if they counted equally. Recency weighting is what makes calibration track a shifting population instead of averaging over its whole history. |
//! | [`calibration_property_decile_bins`] | risk | The probabilities the fitted constant produces mean what they say: sorted into deciles, every bin's mean predicted probability sits close to the rate at which its entries actually turned out adverse. Recovering the right constant is not the goal in itself — the goal is that a host reading a risk of one in five can act as though one in five is what it will be. |

//! Platt calibration fitting (´alg:platt:fitting´).
//!
//! This module performs golden-section-based Platt scaling to calibrate
//! the logistic model's raw scores into well-calibrated probabilities.
//! The algorithm fits two independent κ values — one for the sister-dominated
//! regime and one for the anchor-dominated regime — using per-regime weighted
//! binary cross-entropy as the objective.
//!
//! # Algorithm
//!
//! Three-phase approach:
//! 1. **Pre-scan:** reverse-iterate the buffer to compute per-entry combined
//!    weights (regime × recency × importance). Compute per-regime effective
//!    sample counts.
//! 2. **Per-regime golden section:** for each eligible regime, search
//!    `log κ ∈ [log 0.01, log 100]` to minimise weighted cross-entropy.
//! 3. **Post-fit:** assemble `PlattRefitResult` with `δ_cal = max |ln κ_new − ln κ_old|`.
//!
//! # Cross-References
//!
//! - (´dec:calibration:per-regime-search´) — why the fit is a factored
//!   per-regime search rather than one joint optimisation
//! - (´sec:platt:calibration´) — the calibration division of the risk models
//! - (´dec:health:calibration-settled-cuts´) — when calibration is called
//!   settled, on movement and on count together

