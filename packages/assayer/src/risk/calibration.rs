// Phase 2: Golden Section Search
// ═══════════════════════════════════════════════════════════════════════════════

/// Fits a single regime's κ via golden section search on log(κ).
///
/// The objective is the weighted binary cross-entropy loss. Golden
/// section search finds the minimum of a unimodal function on an
/// interval. The loss is unimodal in log(κ) for any non-degenerate
/// score distribution.
///
/// Returns the optimal κ value.
///
/// The per-regime search is the fit's second phase (´alg:platt:fitting´).
#[allow(clippy::suboptimal_flops)] // Justified: mul_add fuses the golden-section update's rounding and drifts Platt calibration against pinned regression oracles; the plain form is the calibrated arithmetic
fn fit_single_regime(entries: &[PrecomputedEntry], regime: RegimeSelector, config: &PlattConfig) -> f64 {
    let log_lo = config.kappa_min.ln();
    let log_hi = config.kappa_max.ln();

    // Golden ratio inverse: 1/φ = 2/(1+√5) ≈ 0.618
    let inv_phi = 2.0 / (1.0 + 5.0_f64.sqrt());

    let loss_at = |log_kappa: f64| -> f64 { regime_loss(entries, regime, log_kappa.exp()) };

    let mut a = log_lo;
    let mut b = log_hi;
    let mut x1 = b - inv_phi * (b - a);
    let mut x2 = a + inv_phi * (b - a);
    let mut f1 = loss_at(x1);
    let mut f2 = loss_at(x2);

    for _ in 0..config.max_golden_iterations {
        if (b - a).abs() < config.golden_tolerance {
            break;
        }
        if f1 < f2 {
            b = x2;
            x2 = x1;
            f2 = f1;
            x1 = b - inv_phi * (b - a);
            f1 = loss_at(x1);
        } else {
            a = x1;
            x1 = x2;
            f1 = f2;
            x2 = a + inv_phi * (b - a);
            f2 = loss_at(x2);
        }
    }

    f64::midpoint(a, b).exp()
}

/// Evaluates the weighted binary cross-entropy for one regime at a given κ.
///
/// Single pass over the buffer. Entries with combined weight < 10⁻²⁰
/// are skipped.
///
/// The per-regime search is the fit's second phase (´alg:platt:fitting´).
fn regime_loss(entries: &[PrecomputedEntry], regime: RegimeSelector, kappa: f64) -> f64 {
    let mut loss = 0.0;
    let inv_kappa = 1.0 / kappa;

    for e in entries {
        let w = match regime {
            RegimeSelector::Sister => e.sister_weight,
            RegimeSelector::Anchor => e.anchor_weight,
        };
        if w < 1e-20 {
            continue;
        }

        let p = sigmoid_clamped(e.rho * inv_kappa);

        let entry_loss = if e.positive { -p.ln() } else { -(1.0 - p).ln() };

        loss = w.mul_add(entry_loss, loss);
    }
    loss
}

